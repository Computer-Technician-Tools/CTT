/**
 * Generate a tiny browser-side icon module from the installed Iconify collections.
 * The full collections contain thousands of icons; CTT only needs the icons
 * referenced by PlatformBadges plus any explicit BrandLogo names listed here.
 */
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const platformSource = await readFile(path.join(root, 'src/components/PlatformBadges/index.tsx'), 'utf8');
const collections = {
  simpleIcons: '@iconify-json/simple-icons/icons.json',
  logos: '@iconify-json/logos/icons.json',
  materialSymbols: '@iconify-json/material-symbols/icons.json',
};
const used = Object.fromEntries(Object.keys(collections).map((key) => [key, new Set()]));
const candidatePattern = /\{\s*set:\s*(simpleIcons|logos|materialSymbols)\s*,\s*names:\s*\[([^\]]*)\]\s*\}/g;
for (const match of platformSource.matchAll(candidatePattern)) {
  for (const name of match[2].matchAll(/['"]([^'"]+)['"]/g)) {
    const value = name[1].trim().toLowerCase().replace(/[\s_]+/g, '-');
    used[match[1]].add(value);
    used[match[1]].add(value.replace(/-/g, ''));
  }
}
// Keep BrandLogo useful for common CTT brands without shipping the entire set.
for (const name of ['github', 'gitlab', 'docker', 'linux', 'windows', 'apple', 'google', 'microsoft', 'nvidia', 'amd', 'intel', 'mozilla', 'firefox', 'chrome', 'steam', 'discord', 'youtube', 'wikipedia', 'proxmox', 'synology']) {
  used.simpleIcons.add(name);
  used.simpleIcons.add(name.replace(/-/g, ''));
}

// The platform badge configuration also refers to these sets. Collect every
// referenced candidate rather than relying on the narrow legacy array scan;
// this keeps all fallback artwork in the generated browser bundle.
for (const match of platformSource.matchAll(/\{\s*set:\s*(simpleIconSet|logoSet|materialSymbolSet)\s*,\s*names:\s*\[([^\]]*)\]\s*\}/g)) {
  const setName = match[1] === 'simpleIconSet' ? 'simpleIcons' :
    match[1] === 'logoSet' ? 'logos' : 'materialSymbols';
  for (const name of match[2].matchAll(/['"]([^'"]+)['"]/g)) {
    const value = name[1].trim().toLowerCase().replace(/[\s_]+/g, '-');
    used[setName].add(value);
    used[setName].add(value.replace(/-/g, ''));
  }
}

const output = {};
for (const [key, packagePath] of Object.entries(collections)) {
  const collection = JSON.parse(await readFile(path.join(root, 'node_modules', packagePath), 'utf8'));
  const icons = {};
  for (const name of used[key]) {
    const icon = collection.icons?.[name];
    if (icon) icons[name] = icon;
  }
  output[key] = {width: collection.width ?? 24, height: collection.height ?? 24, icons};
  console.log(`${key}: ${Object.keys(icons).length} icons retained`);
}
const target = path.join(root, 'src/generated/platform-icons.ts');
await mkdir(path.dirname(target), {recursive: true});
await writeFile(target, `/* Generated by scripts/generate-icon-subset.mjs. Do not edit manually. */\n` +
  Object.entries(output).map(([key, value]) => `export const ${key} = ${JSON.stringify(value)} as const;`).join('\n') + '\n');
